#!/usr/bin/env python3
"""Re-assemble the bundled HyperBoot / HyperKernel sources with NASM and
regenerate hyperos/prebuilt.py.

The prebuilt binaries let Hyper OS Creator build bootable systems on
machines that do not have NASM installed. Run this after editing any
file in hyperos/asm/.
"""
import base64
import pathlib
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
ASM = ROOT / "hyperos" / "asm"
OUT = ROOT / "hyperos" / "prebuilt.py"
SOURCES = {"HYPERBOOT": "hyperboot.asm", "HYPERSPLASH": "bootmsg.asm", "HYPERKERNEL": "hyperkernel.asm"}


def assemble(src: pathlib.Path) -> bytes:
    with tempfile.TemporaryDirectory() as tmp:
        out = pathlib.Path(tmp) / "out.bin"
        subprocess.run(["nasm", "-f", "bin", str(src), "-o", str(out)], check=True)
        return out.read_bytes()


def render() -> str:
    lines = [
        '"""Prebuilt binaries assembled from hyperos/asm/*.asm.',
        "",
        "AUTO-GENERATED by tools/build_prebuilt.py - do not edit by hand.",
        '"""',
        "import base64",
        "",
    ]
    for name, file in SOURCES.items():
        data = base64.b64encode(assemble(ASM / file)).decode()
        chunks = [data[i:i + 76] for i in range(0, len(data), 76)]
        lines.append(f"{name} = base64.b64decode(")
        lines += [f'    "{c}"' for c in chunks]
        lines.append(")")
        lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.read_text() == text else "prebuilt.py is out of date")
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
